import os
import json
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# Configuration
FS = 120.0
DT = 1.0 / FS

def main():
    workspace_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    raw_csv_path = os.path.join(workspace_root, "data/Canoe_xsens_dot_raw.csv")
    filt_csv_path = os.path.join(workspace_root, "reference/filtered_imu_data.csv")
    metrics_csv_path = os.path.join(workspace_root, "reference/stroke_metrics_cpp.csv")
    output_dir = os.path.join(workspace_root, "reference")
    plots_dir = os.path.join(output_dir, "stroke_plots_filtered")
    os.makedirs(plots_dir, exist_ok=True)

    print("Loading datasets generated by C++ pipeline...")
    # Load raw data, filtered data and metrics
    raw_df = pd.read_csv(raw_csv_path)
    filt_df = pd.read_csv(filt_csv_path)
    result = pd.read_csv(metrics_csv_path)
    
    n = len(raw_df)
    acc_y_raw = raw_df["Acc_Y"].to_numpy()
    acc_y_filt = filt_df["Acc_Y"].to_numpy()

    # 1. Generate Static Overview Plot
    print("Generating static overview plot...")
    plt.figure(figsize=(15, 6))
    time_s = np.arange(n) * DT
    plt.plot(time_s, acc_y_raw, label="Raw Acc_Y", color="gray", alpha=0.3, linestyle="--")
    plt.plot(time_s, acc_y_filt, label="Filtered Acc_Y", color="blue", linewidth=1.5)
    
    # Mark peaks and zero crossings
    for idx, row in result.iterrows():
        a_s = int(row["accel_start_idx"])
        d_s = int(row["decel_start_idx"])
        d_e = int(row["decel_end_idx"])
        pos_p = int(row["pos_peak_idx"])
        neg_p = int(row["neg_peak_idx"])

        plt.scatter([a_s * DT], [acc_y_filt[a_s]], color="green", marker="^", s=40, zorder=5)
        plt.scatter([d_s * DT], [acc_y_filt[d_s]], color="red", marker="v", s=40, zorder=5)
        plt.scatter([d_e * DT], [acc_y_filt[d_e]], color="black", marker="x", s=40, zorder=5)
        plt.scatter([pos_p * DT], [row["accY_pos_peak"]], color="darkgreen", marker="o", s=30, zorder=5)
        plt.scatter([neg_p * DT], [row["accY_neg_peak"]], color="darkred", marker="o", s=30, zorder=5)

    plt.title("Overview: Raw vs. Causal Adaptive Filtered Acc_Y and Stroke Segmentation")
    plt.xlabel("Time (seconds)")
    plt.ylabel("Acceleration (m/s²)")
    plt.grid(True, linestyle="--", alpha=0.5)
    plt.legend(["Raw Acc_Y", "Filtered Acc_Y", "Accel Start", "Decel Start", "Decel End", "Pos Peak", "Neg Peak"])
    plt.tight_layout()
    overview_path = os.path.join(output_dir, "stroke_segmentation_plot_filtered.png")
    plt.savefig(overview_path, dpi=150)
    plt.close()
    print(f"Saved overview plot to {overview_path}")

    # 2. Generate Individual Stroke Plots
    print("Generating individual stroke plots...")
    for idx, row in result.iterrows():
        sid = int(row["stroke_id"])
        a_s = int(row["accel_start_idx"])
        a_e = int(row["accel_end_idx"])
        d_s = int(row["decel_start_idx"])
        d_e = int(row["decel_end_idx"])
        
        pad = 10
        plot_start = max(0, a_s - pad)
        plot_end = min(n, d_e + pad)
        
        local_time = np.arange(plot_start, plot_end) * DT
        local_raw = acc_y_raw[plot_start:plot_end]
        local_filt = acc_y_filt[plot_start:plot_end]
        
        plt.figure(figsize=(8, 4))
        plt.plot(local_time, local_raw, label="Raw Acc_Y", color="gray", alpha=0.4, linestyle="--")
        plt.plot(local_time, local_filt, label="Filtered Acc_Y", color="blue", linewidth=2)
        
        plt.axvspan(a_s * DT, a_e * DT, color="green", alpha=0.1, label="Accel Phase")
        plt.axvspan(d_s * DT, d_e * DT, color="red", alpha=0.1, label="Decel Phase")
        
        plt.scatter([a_s * DT], [acc_y_filt[a_s]], color="green", marker="^", s=80, zorder=5, label="Accel Start")
        plt.scatter([d_s * DT], [acc_y_filt[d_s]], color="red", marker="v", s=80, zorder=5, label="Decel Start")
        plt.scatter([d_e * DT], [acc_y_filt[d_e]], color="black", marker="x", s=80, zorder=5, label="Decel End")
        
        plt.scatter([int(row["pos_peak_idx"]) * DT], [row["accY_pos_peak"]], color="darkgreen", marker="o", s=80, zorder=5, label=f"Pos Peak ({row['accY_pos_peak']:.2f})")
        plt.scatter([int(row["neg_peak_idx"]) * DT], [row["accY_neg_peak"]], color="darkred", marker="o", s=80, zorder=5, label=f"Neg Peak ({row['accY_neg_peak']:.2f})")
        
        plt.title(f"Stroke {sid:03d} (Total Duration: {row['TotalTime_s']:.2f}s)")
        plt.xlabel("Time (seconds)")
        plt.ylabel("Acceleration (m/s²)")
        plt.legend(loc="upper right", fontsize="small")
        plt.grid(True, linestyle="--", alpha=0.5)
        plt.tight_layout()
        
        stroke_plot_path = os.path.join(plots_dir, f"stroke_{sid:03d}.png")
        plt.savefig(stroke_plot_path, dpi=100)
        plt.close()
    print(f"Generated {len(result)} individual stroke plots in {plots_dir}")

    # 3. Generate Interactive HTML Dashboard
    print("Generating interactive HTML dashboard...")
    # Prepare data for dashboard
    time_series_data = {
        "time_s": (np.arange(n) * DT).tolist(),
        "acc_y_raw": acc_y_raw.tolist(),
        "acc_y_filt": acc_y_filt.tolist(),
        "cutoffs": filt_df["Cutoff"].tolist()
    }
    
    # Save the CSV clean result columns
    save_cols = [c for c in result.columns if not c.endswith("_idx")]
    result_to_save = result[save_cols]
    
    strokes_list = result.to_dict(orient="records")
    
    # Calculate statistics
    stats_rows = []
    numeric_cols = result_to_save.select_dtypes(include=[np.number]).columns
    for col in numeric_cols:
        if col == "stroke_id":
            continue
        stats_rows.append({
            "Metric": col,
            "Mean": result_to_save[col].mean(),
            "StdDev": result_to_save[col].std(),
            "Min": result_to_save[col].min(),
            "Max": result_to_save[col].max(),
            "Median": result_to_save[col].median()
        })
    stats_df = pd.DataFrame(stats_rows)
    stats_df.to_csv(os.path.join(output_dir, "stroke_metrics_statistics.csv"), index=False)
    
    stats_list = stats_df.to_dict(orient="records")

    template_path = os.path.join(workspace_root, "src/dashboard_template.html")
    with open(template_path, "r", encoding="utf-8") as f:
        dashboard_html = f.read()

    dashboard_html = dashboard_html.replace("__SERIES_DATA__", json.dumps(time_series_data))
    dashboard_html = dashboard_html.replace("__STROKES_DATA__", json.dumps(strokes_list))
    dashboard_html = dashboard_html.replace("__STATS_DATA__", json.dumps(stats_list))
    
    dashboard_path = os.path.join(output_dir, "dashboard.html")
    with open(dashboard_path, "w", encoding="utf-8") as f:
        f.write(dashboard_html)
    print(f"Saved interactive HTML dashboard to {dashboard_path}")

    # 4. Generate Beautifully Formatted Excel Report
    print("Generating beautifully formatted Excel report...")
    try:
        import openpyxl
        from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
        from openpyxl.utils import get_column_letter

        # Calculate statistics
        stats_dict = {}
        for col in result_to_save.columns:
            if col == "stroke_id":
                continue
            stats_dict[col] = {
                "Mean": result_to_save[col].mean(),
                "StdDev": result_to_save[col].std(),
                "Min": result_to_save[col].min(),
                "Max": result_to_save[col].max(),
                "Median": result_to_save[col].median()
            }

        # Define groupings and labels
        excel_groups = [
            {
                "name": "1. Acceleration Phase",
                "metrics": [
                    ("accel_duration_s", "Acceleration phase duration (s)"),
                    ("accY_pos_peak", "ACC-Y positive peak (m/s²)"),
                    ("t_to_pos_peak_pct", "Time to ACC-Y positive peak (%)"),
                    ("RAD", "Rate of acceleration development (RAD)"),
                    ("accel_velocity_integral", "Change in velocity (ACC-Y Acceleration integral) (m/s)"),
                    ("accel_MAC_accX", "Mean absolute change of ACC-X"),
                    ("accel_MAC_gyrX", "Mean absolute change of Gyr-X"),
                    ("accel_MAC_gyrY", "Mean absolute change of Gyr-Y"),
                    ("accel_MAC_gyrZ", "Mean absolute change of Gyr-Z")
                ]
            },
            {
                "name": "2. Deceleration Phase",
                "metrics": [
                    ("decel_duration_s", "Deceleration phase duration (s)"),
                    ("accY_neg_peak", "ACC-Y negative peak (m/s²)"),
                    ("t_to_neg_peak_pct", "Time to ACC-Y negative peak (%)"),
                    ("decel_velocity_integral", "Change in velocity (ACC-Y deceleration integral) (m/s)"),
                    ("decel_MAC_accX", "Mean absolute change of ACC-X"),
                    ("decel_MAC_gyrX", "Mean absolute change of Gyr-X"),
                    ("decel_MAC_gyrY", "Mean absolute change of Gyr-Y"),
                    ("decel_MAC_gyrZ", "Mean absolute change of Gyr-Z")
                ]
            },
            {
                "name": "3. Stroke Phase (Acceleration + Deceleration)",
                "metrics": [
                    ("stroke_gyrX_pos_peak", "Gyr-X positive peak (deg/s)"),
                    ("stroke_gyrX_neg_peak", "Gyr-X Negative peak (deg/s)"),
                    ("stroke_MAC_accX", "Mean absolute change of ACC-X"),
                    ("stroke_MAC_gyrX", "Mean absolute change of Gyr-X"),
                    ("stroke_MAC_gyrY", "Mean absolute change of Gyr-Y"),
                    ("stroke_MAC_gyrZ", "Mean absolute change of Gyr-Z")
                ]
            },
            {
                "name": "4. Consolidated Summary Metrics",
                "metrics": [
                    ("TotalTime_s", "TotalTime: Duration of stroke cycle (s)"),
                    ("TimeToPosPeak_s", "TimeToPosPeak: Time from start to positive peak (s)"),
                    ("TimeToNegPeak_s", "TimeToNegPeak: Time from mid zero to negative peak (s)"),
                    ("Area_Positive", "Area_Positive: Integrated positive acceleration area (m/s)"),
                    ("Area_Negative", "Area_Negative: Integrated negative acceleration area (m/s)")
                ]
            }
        ]

        wb = openpyxl.Workbook()
        ws1 = wb.active
        ws1.title = "Summary Statistics"
        ws1.views.sheetView[0].showGridLines = True

        title_font = Font(name="Segoe UI", size=16, bold=True, color="FFFFFF")
        title_fill = PatternFill(start_color="2C3E50", end_color="2C3E50", fill_type="solid")
        align_center = Alignment(horizontal="center", vertical="center")

        ws1.merge_cells("A1:F2")
        ws1["A1"] = "Canoe IMU Performance Analytics Report"
        ws1["A1"].font = title_font
        ws1["A1"].fill = title_fill
        ws1["A1"].alignment = align_center

        meta_font = Font(name="Segoe UI", size=10, italic=True)
        ws1["A3"] = f"Dataset: Canoe_xsens_dot.xlsx  |  Total Strokes: {len(result)}  |  Sample Rate: 120 Hz"
        ws1["A3"].font = meta_font

        section_font = Font(name="Segoe UI", size=12, bold=True, color="FFFFFF")
        section_fill = PatternFill(start_color="16A085", end_color="16A085", fill_type="solid")

        header_font = Font(name="Segoe UI", size=10, bold=True, color="FFFFFF")
        header_fill = PatternFill(start_color="34495E", end_color="34495E", fill_type="solid")

        label_font = Font(name="Segoe UI", size=10, bold=True)
        value_font = Font(name="Segoe UI", size=10)

        thin_border = Border(
            left=Side(style='thin', color='BDC3C7'),
            right=Side(style='thin', color='BDC3C7'),
            top=Side(style='thin', color='BDC3C7'),
            bottom=Side(style='thin', color='BDC3C7')
        )
        zebra_fill = PatternFill(start_color="F8F9FA", end_color="F8F9FA", fill_type="solid")

        current_row = 5
        for gp in excel_groups:
            ws1.merge_cells(start_row=current_row, start_column=1, end_row=current_row, end_column=6)
            cell = ws1.cell(row=current_row, column=1)
            cell.value = gp["name"]
            cell.font = section_font
            cell.fill = section_fill
            cell.alignment = Alignment(vertical="center", indent=1)
            ws1.row_dimensions[current_row].height = 26
            current_row += 1

            headers_cols = ["Metric", "Mean", "StdDev", "Min", "Max", "Median"]
            for col_idx, h in enumerate(headers_cols):
                c = ws1.cell(row=current_row, column=col_idx+1)
                c.value = h
                c.font = header_font
                c.fill = header_fill
                c.alignment = align_center
                c.border = thin_border
            ws1.row_dimensions[current_row].height = 20
            current_row += 1

            for row_idx, (col_name, label) in enumerate(gp["metrics"]):
                row_fill = zebra_fill if row_idx % 2 == 1 else PatternFill(fill_type=None)
                
                cell_lbl = ws1.cell(row=current_row, column=1)
                cell_lbl.value = label
                cell_lbl.font = label_font if "peak" in label.lower() or "duration" in label.lower() else value_font
                cell_lbl.fill = row_fill
                cell_lbl.border = thin_border
                cell_lbl.alignment = Alignment(vertical="center", indent=1)

                stats = stats_dict.get(col_name, {"Mean": 0.0, "StdDev": 0.0, "Min": 0.0, "Max": 0.0, "Median": 0.0})
                stats_cols = ["Mean", "StdDev", "Min", "Max", "Median"]

                for col_idx, key in enumerate(stats_cols):
                    cell_val = ws1.cell(row=current_row, column=col_idx+2)
                    cell_val.value = stats[key]
                    cell_val.font = value_font
                    cell_val.fill = row_fill
                    cell_val.border = thin_border
                    cell_val.alignment = Alignment(horizontal="right", vertical="center")

                    if "pct" in col_name or "percent" in label.lower():
                        cell_val.number_format = '0.0"%"'
                    elif "duration" in col_name or "Time" in col_name:
                        cell_val.number_format = '0.000'
                    elif "peak" in col_name or "integral" in col_name or "Area" in col_name:
                        cell_val.number_format = '0.00'
                    else:
                        cell_val.number_format = '0.0000'

                ws1.row_dimensions[current_row].height = 18
                current_row += 1
            current_row += 2

        # Sheet 2: Per-Stroke Metrics
        ws2 = wb.create_sheet(title="Per-Stroke Metrics")
        ws2.views.sheetView[0].showGridLines = True

        ws2.merge_cells("A1:AC2")
        ws2["A1"] = f"Per-Cycle Performance Log (All {len(result)} Strokes)"
        ws2["A1"].font = title_font
        ws2["A1"].fill = title_fill
        ws2["A1"].alignment = align_center

        headers = list(result_to_save.columns)
        for col_idx, col_name in enumerate(headers):
            c = ws2.cell(row=4, column=col_idx+1)
            c.value = col_name
            c.font = header_font
            c.fill = header_fill
            c.alignment = align_center
            c.border = thin_border
        ws2.row_dimensions[4].height = 24

        for row_idx, row in result_to_save.iterrows():
            r_idx = row_idx + 5
            row_fill = zebra_fill if row_idx % 2 == 1 else PatternFill(fill_type=None)
            for col_idx, col_name in enumerate(headers):
                c = ws2.cell(row=r_idx, column=col_idx+1)
                c.value = row[col_name]
                c.font = value_font
                c.fill = row_fill
                c.border = thin_border

                if col_idx == 0:
                    c.alignment = align_center
                    c.number_format = '0'
                else:
                    c.alignment = Alignment(horizontal="right", vertical="center")
                    if "pct" in col_name:
                        c.number_format = '0.0"%"'
                    elif "duration" in col_name or "Time" in col_name:
                        c.number_format = '0.000'
                    elif "peak" in col_name or "integral" in col_name or "Area" in col_name or "RAD" in col_name:
                        c.number_format = '0.00'
                    else:
                        c.number_format = '0.0000'
            ws2.row_dimensions[r_idx].height = 18

        for ws in [ws1, ws2]:
            for col in ws.columns:
                max_len = 0
                col_letter = get_column_letter(col[0].column)
                for cell in col:
                    if cell.row in [1, 2, 5, 16, 26, 34]:
                        continue
                    val_str = str(cell.value or '')
                    if len(val_str) > max_len:
                        max_len = len(val_str)
                if ws == ws1 and col_letter == 'A':
                    ws.column_dimensions[col_letter].width = 56
                else:
                    ws.column_dimensions[col_letter].width = max(max_len + 4, 12)

        excel_out_path = os.path.join(output_dir, "stroke_statistics_report.xlsx")
        wb.save(excel_out_path)
        print(f"Saved formatted Excel report to {excel_out_path}")
    except Exception as e:
        print(f"Warning: Could not save formatted Excel file: {e}")

    print("Done!")

if __name__ == "__main__":
    main()
