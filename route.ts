import { NextResponse } from 'next/server';
import { exec } from 'child_process';
import util from 'util';
import fs from 'fs/promises';
import path from 'path';
import Papa from 'papaparse'; // npm install papaparse

const execPromise = util.promisify(exec);

export async function POST(req: Request) {
  try {
    const formData = await req.formData();
    const file = formData.get('file') as File;

    if (!file) {
      return NextResponse.json({ error: 'No file uploaded' }, { status: 400 });
    }

    // 1. Save uploaded file temporarily to your server's data folder
    const buffer = Buffer.from(await file.arrayBuffer());
    const uploadDir = path.join(process.cwd(), 'data');
    const resultsDir = path.join(process.cwd(), 'results');
    
    await fs.mkdir(uploadDir, { recursive: true });
    await fs.mkdir(resultsDir, { recursive: true });

    const inputFilePath = path.join(uploadDir, 'uploaded_stroke.csv');
    await fs.writeFile(inputFilePath, buffer);

    // 2. Run your Docker container with absolute paths mapped to host folders
    // Note: Ensure your web app process has permission to run docker commands
    const dockerCmd = `docker run --rm \
      -v ${uploadDir}:/workspace/data \
      -v ${resultsDir}:/workspace/results \
      dragon-boat-app --input data/uploaded_stroke.csv --output results`;

    await execPromise(dockerCmd);

    // 3. Read the output CSV generated by your C++ app
    const outputCsvPath = path.join(resultsDir, 'stroke_full_cycles.csv');
    const csvFileContent = await fs.readFile(outputCsvPath, 'utf8');

    // 4. Parse CSV into JSON using PapaParse
    const parsedData = Papa.parse(csvFileContent, {
      header: true,
      dynamicTyping: true, // Automatically converts numbers from strings
    });

    // 5. Return parsed stroke metrics to the v0 frontend
    return NextResponse.json({
      success: true,
      metrics: parsedData.data,
      plotsUrl: '/results/strokes_overview.png' // or individual plots path
    });

  } catch (error: any) {
    console.error('Analysis error:', error);
    return NextResponse.json({ error: error.message || 'Internal Server Error' }, { status: 500 });
  }
}